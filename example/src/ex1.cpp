#include <iostream>
using namespace std;

int main()
{
	int a = 10;
	int* p = &a;   // 포인터    : 주소를 담는 변수
	int& r = a;    // 참조자    : 변수의 또 다른 이름(별명)

	bool b = true; // C++ 의 참/거짓 자료형

	cout << a << ',' << *p << ',' << r << endl;   // 값   : 셋 다 10
	cout << &a << ',' << p << ',' << &r << endl;  // 주소 : 셋 다 같은 주소

	r = 20;        // 참조자를 바꾸면 원본 a 가 바뀐다
	cout << a << endl;

	if (b)
		cout << "true" << endl;
	cout << b << endl;      // 1
	cout << false << endl;  // 0
}

